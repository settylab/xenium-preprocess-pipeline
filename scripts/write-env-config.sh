#!/usr/bin/env bash
# scripts/write-env-config.sh — the final step of installation: records
# RESOLVED ABSOLUTE values into the gitignored scripts/env.local.conf,
# so every sbatch job reads a fixed, already-resolved config instead of
# re-deriving `$HOME`-relative paths inside its own (possibly different)
# environment instance. See scripts/lib/env_config.sh for the consumer
# side and the full rationale.
#
# Usage:
#   scripts/write-env-config.sh \
#       --env-prefix   /abs/path/to/micromamba/envs/xenium \
#       --r-lib-dir    /abs/path/to/R/library \
#       [--r-module    fhR/4.4.1-foss-2023b] \
#       [--micromamba-bin /abs/path/to/micromamba]
#
# --env-prefix and --r-lib-dir must already exist (this script records,
# it does not create, the environment — run the install steps in
# docs/installation.md first). --r-module defaults to the module this
# pipeline has always assumed; --micromamba-bin auto-detects via
# `command -v micromamba` if not passed.
#
# --env-name <name> is an alternative to --env-prefix: it reads back
# the prefix that `scripts/create-env.sh -n <name> ...` recorded to
# `scripts/.env-prefix-<name>` at env-creation time, instead of you
# having to resolve the path yourself. (Unrelated to the deprecated
# `--env-name`/`$ENV_NAME` accepted by the sbatch submit scripts — see
# their own header comments; this is write-env-config.sh's only use of
# the name.) Pass at most one of --env-prefix / --env-name.

set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
OUT="$SCRIPT_DIR/env.local.conf"

ENV_PREFIX=""
ENV_NAME=""
R_LIB_DIR=""
R_MODULE="fhR/4.4.1-foss-2023b"
MICROMAMBA_BIN=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        --env-prefix)      ENV_PREFIX="$2"; shift 2 ;;
        --env-name)        ENV_NAME="$2"; shift 2 ;;
        --r-lib-dir)       R_LIB_DIR="$2"; shift 2 ;;
        --r-module)        R_MODULE="$2"; shift 2 ;;
        --micromamba-bin)  MICROMAMBA_BIN="$2"; shift 2 ;;
        -h|--help)
            sed -n '2,28p' "$0"; exit 0 ;;
        *)
            echo "error: unknown argument: $1" >&2; exit 2 ;;
    esac
done

if [[ -n "$ENV_PREFIX" && -n "$ENV_NAME" ]]; then
    echo "error: pass at most one of --env-prefix / --env-name, not both." >&2
    exit 2
fi

if [[ -n "$ENV_NAME" ]]; then
    RECEIPT="$SCRIPT_DIR/.env-prefix-$ENV_NAME"
    if [[ ! -f "$RECEIPT" ]]; then
        echo "error: --env-name $ENV_NAME: no receipt at $RECEIPT" >&2
        echo "       Run scripts/create-env.sh -n $ENV_NAME -f environments/xenium.yml first" >&2
        echo "       (it writes this file), or pass --env-prefix directly." >&2
        exit 3
    fi
    ENV_PREFIX=$(<"$RECEIPT")
fi

: "${ENV_PREFIX:?--env-prefix or --env-name is required}"
: "${R_LIB_DIR:?--r-lib-dir is required (absolute path to the R library holding spacexr/SPLIT)}"

if [[ ! -d "$ENV_PREFIX" ]]; then
    echo "error: --env-prefix does not exist: $ENV_PREFIX" >&2
    echo "       Create it first (scripts/create-env.sh -n xenium -f environments/xenium.yml)." >&2
    exit 3
fi
ENV_PREFIX=$(cd "$ENV_PREFIX" && pwd)   # canonicalize to an absolute path

if [[ ! -d "$R_LIB_DIR" ]]; then
    echo "error: --r-lib-dir does not exist: $R_LIB_DIR" >&2
    echo "       Create it and install spacexr/SPLIT/Seurat into it first (docs/installation.md § R side)." >&2
    exit 3
fi
R_LIB_DIR=$(cd "$R_LIB_DIR" && pwd)

if [[ -z "$MICROMAMBA_BIN" ]]; then
    if ! MICROMAMBA_BIN=$(command -v micromamba); then
        echo "error: micromamba not found on PATH and --micromamba-bin not given." >&2
        exit 4
    fi
fi
if [[ ! -x "$MICROMAMBA_BIN" ]]; then
    echo "error: --micromamba-bin is not executable: $MICROMAMBA_BIN" >&2
    exit 4
fi
# Canonicalize (command -v can return a relative-looking path on some shells).
MICROMAMBA_BIN=$(cd "$(dirname "$MICROMAMBA_BIN")" && pwd)/$(basename "$MICROMAMBA_BIN")

cat > "$OUT" <<EOF
# Generated by scripts/write-env-config.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).
# Machine-local, gitignored — resolved ABSOLUTE values for THIS install.
# Do not hand-edit; re-run scripts/write-env-config.sh instead.
MICROMAMBA_BIN=$MICROMAMBA_BIN
XENIUM_ENV_PREFIX=$ENV_PREFIX
R_LIB_DIR=$R_LIB_DIR
R_MODULE=$R_MODULE
EOF

echo "[write-env-config] wrote $OUT:"
sed 's/^/[write-env-config]   /' "$OUT"
echo "[write-env-config] verify with: scripts/env-preflight.sh"
